# 指数（用于计算相对收益/beta 基准）
INDEX_CODES: list[tuple[str, str, str]] = [
    ("000300", "沪深300", "sh"),
    ("000001", "上证指数", "sh"),
]

DEFAULT_CODES = DEFAULT_CODES + INDEX_CODES

UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)


def fetch_one(code: str, prefix: str, bars: int, retries: int = 3) -> list[dict]:
    """抓一只股票的日线（前复权）。返回 [{datetime,open,close,high,low,vol}, ...]。"""
    url = f"{API}?symbol={prefix}{code}&scale=240&ma=no&datalen={bars}"
    last_err: Exception | None = None
    for attempt in range(retries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": UA})
            with urllib.request.urlopen(req, timeout=25) as resp:
                raw = resp.read().decode("utf-8")
            # 新浪返回的 JSON 键名无引号（非严格 JSON），需容错解析
            try:
                payload = json.loads(raw)
            except json.JSONDecodeError:
                import re

                fixed = re.sub(r"(\w+):", r'"\1":', raw)
                payload = json.loads(fixed)
            if not payload:
                return []
            rows: list[dict] = []
            for r in payload:
                try:
                    rows.append(
                        {
                            "datetime": f"{r['day']}T00:00:00",
                            "open": float(r["open"]),
                            "close": float(r["close"]),
                            "high": float(r["high"]),
                            "low": float(r["low"]),
                            "vol": float(r.get("volume", 0)),
                        }
                    )
                except (KeyError, ValueError, TypeError):
                    continue
            return rows
        except Exception as e:  # noqa: BLE001
            last_err = e
            time.sleep(1.5 * (attempt + 1))
    print(f"  ❌ {code} 抓取失败: {last_err}")
    return []


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bars", type=int, default=1500, help="抓取根数（新浪上限约 1500，约 6 年）")
    ap.add_argument("--codes", nargs="*", default=None, help="只抓指定代码（默认抓全部）")
    ap.add_argument("--force", action="store_true", help="忽略缓存重新抓取")
    ap.add_argument("--extra", action="store_true", help="只抓 EXTRA_CODES（V733 扩样）")
    ap.add_argument("--all", action="store_true", help="抓全部（DEFAULT + EXTRA，去重）")
    args = ap.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    targets = DEFAULT_CODES
    if args.extra:
        targets = EXTRA_CODES + INDEX_CODES
    elif args.all:
        # 去重（EXTRA 与 DEFAULT 有重叠，如 002594/300750 等）
        seen: set[tuple[str, str, str]] = set()
        merged = []
        for t in DEFAULT_CODES + EXTRA_CODES:
            if t not in seen:
                seen.add(t)
                merged.append(t)
        targets = merged
    if args.codes:
        targets = [t for t in targets if t[0] in args.codes]

    ok = 0
    for code, name, prefix in targets:
        out = OUT_DIR / f"{prefix}{code}_daily.json"
        if out.exists() and not args.force:
            rows = json.loads(out.read_text(encoding="utf-8"))
            print(f"  ⏭  {prefix}{code} {name} 缓存 {len(rows)} 根")
            ok += 1
            continue
        rows = fetch_one(code, prefix, args.bars)
        if not rows:
            continue
        out.write_text(json.dumps(rows, ensure_ascii=False), encoding="utf-8")
        print(
            f"  ✅ {prefix}{code} {name} {len(rows)} 根  "
            f"{rows[0]['datetime'][:10]} → {rows[-1]['datetime'][:10]}"
        )
        ok += 1
        time.sleep(0.3)

    print(f"\n完成：{ok}/{len(targets)} 只 → {OUT_DIR}")
    return 0 if ok == len(targets) else 1


if __name__ == "__main__":
    raise SystemExit(main())
